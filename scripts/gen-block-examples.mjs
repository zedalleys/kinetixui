/**
 * gen-block-examples.mjs — turn the real Block source files into the snippets the website shows.
 *
 *   node scripts/gen-block-examples.mjs           write the generated module
 *   node scripts/gen-block-examples.mjs --check   fail if it is stale (CI)
 *
 * The website used to carry a hand-written copy of every block's code for every platform, next to a separate
 * hand-written preview of the same block. Two copies, no check, and they had already drifted. Now there is one
 * authoritative file per block per platform — the file a compiler actually sees — and this extracts the
 * documented region out of it. "One source of truth" here means one source file PER PLATFORM IMPLEMENTATION:
 * nothing is transpiled from React into Kotlin or Dart, and this script never writes code, only copies it.
 *
 * Also emits block-parity.json, so coverage counts are derived rather than typed by anyone.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const read = (p) => readFileSync(`${root}/${p}`, "utf8");
const CHECK = process.argv.includes("--check");

const manifest = JSON.parse(read("blocks.manifest.json"));
const platformDefs = JSON.parse(read("components.manifest.json")).platformDefinitions;
const PLATFORM_ORDER = Object.keys(platformDefs);

const OUT_TS = "apps/web/src/registry/block-examples.generated.ts";
const OUT_JSON = "block-parity.json";

/**
 * The text between `kx-block:start` and `kx-block:end`, with the marker lines themselves dropped.
 *
 * The markers exist because a source file needs more than the example: imports, and for the native platforms a
 * test that makes a compiler look at it. The region is what a reader should copy; the rest is what makes it
 * real. Keeping both in ONE file is the point — a separate "clean copy for the docs" would be the duplication
 * this replaces.
 */
function extract(relPath) {
  const text = read(relPath);
  const start = text.indexOf("kx-block:start");
  const end = text.indexOf("kx-block:end");
  if (start === -1 || end === -1 || end < start) throw new Error(`${relPath}: missing kx-block:start / kx-block:end markers`);
  const bodyStart = text.indexOf("\n", start) + 1;
  const bodyEnd = text.lastIndexOf("\n", end);
  const body = text.slice(bodyStart, bodyEnd).replace(/\n+$/, "");
  if (!body.trim()) throw new Error(`${relPath}: the kx-block region is empty`);
  return body;
}

const slugs = Object.keys(manifest.blocks); // manifest order is the page order — deterministic, not sorted by accident
const snippets = {};
const coverage = Object.fromEntries(PLATFORM_ORDER.map((p) => [p, 0]));

for (const slug of slugs) {
  const block = manifest.blocks[slug];
  const perPlatform = {};
  // PLATFORM_ORDER, not Object.keys(sources): the tab order on the site follows the central platform
  // definition, so a block cannot invent its own ordering and the output is stable across regenerations.
  for (const platform of PLATFORM_ORDER) {
    const path = block.sources[platform];
    if (!path) continue;
    perPlatform[platform] = extract(path);
    coverage[platform]++;
  }
  if (Object.keys(perPlatform).length === 0) throw new Error(`${slug}: no sources at all — a block must have at least one real implementation`);
  snippets[slug] = perPlatform;
}

const GENERATED = "GENERATED by `pnpm gen:blocks` from the real source files in blocks.manifest.json. Edit those, not this file.";

const ts = `/**
 * ${GENERATED}
 *
 * Every string below was extracted from a file a compiler or typechecker actually sees, between its
 * \`kx-block:start\` / \`kx-block:end\` markers. Adding a platform to a block means writing that platform's real
 * source and listing it in blocks.manifest.json — never editing this file.
 */
export const blockExampleSource = {
${slugs
  .map(
    (slug) =>
      `  ${JSON.stringify(slug)}: {\n${Object.entries(snippets[slug])
        .map(([platform, code]) => `    ${JSON.stringify(platform)}: ${JSON.stringify(code)},`)
        .join("\n")}\n  },`,
  )
  .join("\n")}
} as const;

export type BlockSlug = keyof typeof blockExampleSource;
`;

const parity = {
  $schema: "https://kinetixui.com/schema/block-parity.json",
  $description: `Derived Block coverage. ${GENERATED} Nothing here is maintained by hand — the website reads these numbers rather than printing its own.`,
  total: slugs.length,
  platforms: PLATFORM_ORDER,
  coverage,
  /** Blocks that carry every platform in PLATFORM_ORDER — today, realistically, none. */
  onEveryPlatform: slugs.filter((s) => PLATFORM_ORDER.every((p) => manifest.blocks[s].sources[p])).length,
  blocks: Object.fromEntries(slugs.map((s) => [s, PLATFORM_ORDER.filter((p) => manifest.blocks[s].sources[p])])),
};

let stale = false;
for (const [file, out] of [
  [OUT_TS, ts],
  [OUT_JSON, JSON.stringify(parity, null, 2) + "\n"],
]) {
  if (CHECK) {
    if (read(file) !== out) {
      console.error(`  ✗ ${file} is stale — run \`pnpm gen:blocks\``);
      stale = true;
    }
  } else writeFileSync(`${root}/${file}`, out);
}
if (stale) process.exit(1);

const summary = PLATFORM_ORDER.map((p) => `${p} ${coverage[p]}`).join(", ");
console.log(`${CHECK ? "check:blocks ok" : "gen:blocks"} — ${slugs.length} blocks (${summary}).`);
