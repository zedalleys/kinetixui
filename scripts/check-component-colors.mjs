/* ----------------------------------------------------------------------- shipped semantic values */

const readJson = (p) => JSON.parse(readFileSync(join(repoRoot, p), "utf8"));
const val = (n) => n?.["$value"] ?? null;

/** hex6 (lowercase) -> role names, across both themes. Only opaque roles: an alpha role is not "a colour". */
function semanticHexTable() {
  const prim = readJson("tokens/primitives/color.json").color;
  const flat = {};
  for (const fam of Object.keys(prim))
    for (const step of Object.keys(prim[fam] ?? {})) {
      const v = val(prim[fam][step]);
      if (typeof v === "string" && v.startsWith("#")) flat[`${fam}.${step}`] = v;
    }

  const table = new Map();
  for (const mode of ["light", "dark"]) {
    const sem = readJson(`tokens/semantic/color.${mode}.json`).color;
    const local = sem.semantic ?? {};
    const resolve = (ref, depth = 0) => {
      if (typeof ref !== "string" || depth > 6) return null;
      if (ref.startsWith("#")) return ref.toLowerCase();
      let m = ref.match(/^\{color\.semantic\.([\w-]+)\}$/);
      if (m) return resolve(val(local[m[1]]), depth + 1);
      m = ref.match(/^\{color\.([\w-]+)\.([\w-]+)\}$/);
      if (m) return flat[`${m[1]}.${m[2]}`]?.toLowerCase() ?? null;
      m = ref.match(/^\{color\.([\w-]+)\}$/);
      if (m) return resolve(val(sem[m[1]]) ?? val(local[m[1]]), depth + 1);
      return null;
    };
    for (const role of Object.keys(sem)) {
      if (role === "semantic" || val(sem[role]) == null) continue;
      const hex = resolve(val(sem[role]));
      if (!hex || hex.length !== 7) continue; // alpha roles (scrim) are not an opaque colour
      const names = table.get(hex) ?? new Set();
      names.add(role);
      table.set(hex, names);
    }
  }
  return table;
}

/* ---------------------------------------------------------------------------------- detection */

const PALETTE = "azure|blue|green|taupe|cream|amber|red|neutral";
const TAILWIND_STOCK = "slate|gray|zinc|stone|orange|yellow|lime|emerald|teal|cyan|sky|indigo|violet|purple|fuchsia|pink|rose";
const UTILITY_PREFIX =
  "bg|text|border|border-[xytblrse]|ring|ring-offset|fill|stroke|from|via|to|outline|divide|decoration|accent|caret|shadow|placeholder";

const RE = {
  primitiveVar: new RegExp(`--(?:(?:${PALETTE})-\\d+|static-[a-z]+)\\b`, "g"),
  // `border-white`, `bg-black/40`, `text-blue-500`, `hover:bg-red-600` — prefix must start a class token.
  paletteUtility: new RegExp(
    `(?<![\\w-])(?:${UTILITY_PREFIX})-(?:(?:${PALETTE}|${TAILWIND_STOCK})-\\d{2,3}|black|white)(?![\\w-])`,
    "g",
  ),
  // hex that is not an HTML numeric reference and not the tail of a word.
  hex: /(?<![\w&#])#([0-9a-fA-F]{3,8})(?![\w-])/g,
  colourFn: /\b(?:rgba?|hsla?|hwb|lab|lch|oklab|oklch|color)\(\s*[-+]?[\d.]/g,
  swiftCtor: /\bColor\(\s*(?:red|white|hue|\.sRGB|UIColor|NSColor)\b|\b(?:UIColor|NSColor)\(/g,
  swiftNamed: /\bColor\.(?:black|white|red|green|blue|gray|orange|yellow|purple|pink)\b/g,
  swiftImplicit: /(?:[(:,]\s*|\[\s*)\.(?:black|white|red|green|blue|gray|orange|yellow|purple|pink)\b/g,
  kotlinNamed: /\bColor\.(?:Black|White|Red|Green|Blue|Gray|DarkGray|LightGray|Yellow|Cyan|Magenta|hsv|hsl)\b/g,
  kotlinCtor: /\bColor\(\s*(?:0x[0-9a-fA-F]+|red\s*=)/g,
  dartNamed: /\bColors\.(?!transparent\b)[a-zA-Z]+/g,
  dartCtor: /\bColor\(\s*0x([0-9a-fA-F]{8})\b|\bColor\.from(?:ARGB|RGBO)\(/g,
};

/** What precedes a `#fragment` that is a link target rather than a colour. */
const FRAGMENT_CONTEXT = /(?:href|to|for|id|aria-[a-z]+|xlinkHref)\s*=\s*\\?["'{`]?$|url\(\s*\\?["']?$/;

const stripComments = (src) =>
  src
    .replace(/\/\*[\s\S]*?\*\//g, (m) => m.replace(/[^\n]/g, " "))
    .split("\n")
    .map((line) => line.replace(/(^|\s)\/\/.*$/, "$1"))
    .join("\n");

const lineOf = (src, index) => src.slice(0, index).split("\n").length;

/** Normalise `#rgb`, `#rgba`, `#rrggbb`, `#rrggbbaa`, `0xAARRGGBB` to [rgb6, alpha-is-zero]. */
function normaliseHex(raw) {
  let h = raw.toLowerCase();
  if (h.length === 3 || h.length === 4) h = [...h].map((c) => c + c).join("");
  if (h.length === 6) return { rgb: h, transparent: false };
  if (h.length === 8) return { rgb: h.slice(0, 6), transparent: h.slice(6) === "00" };
  return null; // not a colour
}

function scanFile(source, family, semantic) {
  const code = stripComments(source);
  const found = []; // { line, kind, text, role? }
  const add = (index, kind, text, role) => found.push({ line: lineOf(code, index), kind, text, role });

  if (family === "web") {
    for (const m of code.matchAll(RE.primitiveVar)) add(m.index, "primitive-var", m[0]);
    for (const m of code.matchAll(RE.paletteUtility)) add(m.index, "palette-utility", m[0]);
    for (const m of code.matchAll(RE.hex)) {
      const n = normaliseHex(m[1]);
      if (!n || n.transparent) continue;
      // `href="#add"`, `url(#clip)`: a fragment identifier that happens to spell hex digits.
      if (FRAGMENT_CONTEXT.test(code.slice(Math.max(0, m.index - 24), m.index))) continue;
      add(m.index, "raw-colour", m[0], semantic.get(`#${n.rgb}`));
    }
    for (const m of code.matchAll(RE.colourFn)) add(m.index, "raw-colour", m[0] + "…");
  } else if (family === "swift") {
    for (const re of [RE.swiftCtor, RE.swiftNamed, RE.swiftImplicit])
      for (const m of code.matchAll(re)) add(m.index, "raw-colour", m[0].trim());
  } else if (family === "kotlin") {
    for (const m of code.matchAll(RE.kotlinNamed)) add(m.index, "raw-colour", m[0]);
    for (const m of code.matchAll(RE.kotlinCtor)) {
      const hex = m[0].match(/0x([0-9a-fA-F]+)/)?.[1];
      if (hex && /^0+$/.test(hex)) continue;
      const role = hex && hex.length === 8 ? semantic.get(`#${hex.slice(2).toLowerCase()}`) : undefined;
      add(m.index, "raw-colour", m[0].trim(), role);
    }
  } else if (family === "dart") {
    for (const m of code.matchAll(RE.dartNamed)) add(m.index, "raw-colour", m[0]);
    for (const m of code.matchAll(RE.dartCtor)) {
      const hex = m[1];
      if (hex && hex.startsWith("00")) continue; // fully transparent
      add(m.index, "raw-colour", m[0].trim(), hex ? semantic.get(`#${hex.slice(2).toLowerCase()}`) : undefined);
    }
  }
  return found;
}

/* ------------------------------------------------------------------------------------ walking */

function* walk(dir, { shallow = false } = {}) {
  if (!existsSync(dir)) return;
  for (const name of readdirSync(dir).sort()) {
    const path = join(dir, name);
    const s = statSync(path);
    if (s.isDirectory()) {
      if (!shallow && name !== "node_modules" && name !== "build" && name !== "dist") yield* walk(path);
    } else yield path;
  }
}

/* ---------------------------------------------------------------------------------------- run */

const semantic = semanticHexTable();
const errors = [];
const notes = [];
const used = new Map(); // allow key -> Set(kinds actually matched)
const scanned = {};

for (const scope of SCOPES) {
  const base = join(root, scope.dir);
  if (!existsSync(base)) {
    if (!fixtureMode) errors.push(`${scope.name}: source directory ${scope.dir} is missing.`);
    continue;
  }
  let count = 0;
  for (const file of walk(base, { shallow: scope.shallow })) {
    const rel = relative(root, file).split("\\").join("/");
    if (!scope.exts.some((e) => file.endsWith(e)) || EXCLUDED_PATH.test(`/${rel}`)) continue;
    const source = readFileSync(file, "utf8");
    if (GENERATED.test(source.slice(0, 600))) continue;
    count++;

    for (const f of scanFile(source, scope.family, semantic)) {
      const allowed = ALLOW[rel];
      if (allowed?.kinds.includes(f.kind)) {
        const set = used.get(rel) ?? new Set();
        set.add(f.kind);
        used.set(rel, set);
        continue;
      }
      const why = f.role
        ? `equals the shipped \`${[...f.role].slice(0, 3).join("`/`")}\`${f.role.size > 3 ? "/…" : ""} role — read the role instead`
        : f.kind === "primitive-var"
          ? "a palette primitive; components consume semantic roles (primitive -> role -> theme -> component)"
          : f.kind === "palette-utility"
            ? "a palette utility; use the semantic role utility (bg-primary, text-muted-foreground, border-border …)"
            : "a raw colour literal; use a semantic role so the theme can change it";
      errors.push(`${rel}:${f.line}  ${f.kind}  \`${f.text}\` — ${why}.`);
    }
  }
  scanned[scope.name] = count;
  if (!fixtureMode && count < scope.min)
    errors.push(`${scope.name}: only ${count} source files scanned under ${scope.dir} (expected >= ${scope.min}) — a broken checkout or a scope that matches nothing is not a clean run.`);
}

if (!fixtureMode) {
  for (const [file, entry] of Object.entries(ALLOW)) {
    if (!existsSync(join(root, file))) {
      errors.push(`allowlist: ${file} no longer exists — remove its entry.`);
      continue;
    }
    const hit = used.get(file) ?? new Set();
    const stale = entry.kinds.filter((k) => !hit.has(k));
    if (stale.length) errors.push(`allowlist: ${file} no longer uses ${stale.join(", ")} — drop it from the entry (the list is documentation, not a permission slip).`);
  }
}

if (errors.length) {
  console.error(`check:component-colors — ${errors.length} problem${errors.length === 1 ? "" : "s"}:\n`);
  for (const e of errors) console.error(`  ✗ ${e}`);
  console.error(
    "\nComponents read colour from semantic roles. If a literal is genuinely required (a picker, a mask, a library selector), add the file to ALLOW in scripts/check-component-colors.mjs with the reason.",
  );
  process.exit(1);
}

const total = Object.values(scanned).reduce((a, b) => a + b, 0);
console.log(
  `check:component-colors — ${total} component sources clean (${Object.entries(scanned)
    .map(([k, v]) => `${k} ${v}`)
    .join(", ")}); ${Object.keys(ALLOW).length} reviewed exceptions.`,
);
for (const n of notes) console.log(`  note: ${n}`);
