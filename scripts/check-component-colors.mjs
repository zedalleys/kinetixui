/**
 * check:component-colors — reusable component source reads colour from semantic roles, not from the
 * palette and not from literals.
 *
 *   node scripts/check-component-colors.mjs              # this repository
 *   node scripts/check-component-colors.mjs --root=<dir> # a fixture tree (see component-colors-guard.test.ts)
 *
 * The architecture is primitive -> semantic role -> theme -> component. The colour-theming audit found
 * that components overwhelmingly honour it, and that this was protected only by someone having looked.
 * A hurried `bg-blue-500`, a pasted `#1d4ed8` or a `Color.white` in a native view does not fail any
 * other gate: it renders correctly in the default theme and stops following the theme the moment a
 * consumer changes one. This is the regression gate for that.
 *
 * WHAT IS CHECKED (per file, comments stripped, one finding per offending line and kind):
 *
 *   primitive-var      a palette custom property: --blue-400, --taupe-100, --static-white …
 *   palette-utility    a Tailwind palette utility: bg-blue-500, text-red-600, border-white, ring-black/40 …
 *   raw-colour         #rgb / #rrggbb / #rrggbbaa, rgb()/rgba()/hsl()/hsla()/oklch()/… with a numeric first
 *                      argument, and the native equivalents: Color(red:), Color(0xFF…), Color.black,
 *                      Colors.white, .black in an argument position, Color.hsv(…)
 *
 * and a raw colour that equals a shipped semantic role (in either theme) is reported as that role, which
 * is the more useful message: "this is --primary, write bg-primary".
 *
 * WHAT IS NOT A FINDING, by construction rather than by allowlist:
 *
 *   fully transparent literals (#0000, 0x00000000, Colors.transparent, Color.Transparent, .clear), because
 *   "no colour" is not a theme decision; `currentColor` and `inherit`; `hsl(var(--role))` and every other
 *   function whose first argument is `var(`; CSS system colours (Canvas, ButtonText, Highlight …), which
 *   are what a forced-colors block is supposed to use; HTML numeric character references (&#10003;).
 *
 * WHAT IS ALLOWLISTED, and why it is the documentation: the entries below are reviewed exceptions. A file
 * here may use the listed kinds anywhere. Each needs a reason a reviewer can disagree with. An entry that
 * no longer matches anything is reported as stale (an error), so the list cannot quietly outlive its need.
 *
 * SCOPE is reusable component source only: packages/ui, packages/iot, packages/ui-angular/src/lib +
 * styles.css, and the three native packages. Generated files (token output), tests, stories, previews,
 * examples and docs are not component source and are not scanned — a docs page may legitimately show a
 * hex to teach it.
 *
 * This is a source check. It cannot see a colour assembled at runtime; the browser gates
 * (check:theme-isolation, check:a11y-site) and the native token tests cover rendered behaviour.
 */
