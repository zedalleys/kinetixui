/**
 * gen-usage-examples.mjs — extract per-demo usage examples from source a compiler actually sees.
 *
 *   node scripts/gen-usage-examples.mjs           write the generated module
 *   node scripts/gen-usage-examples.mjs --check   fail if it is stale (CI)
 *
 * `platform-code.ts` has carried 300 hand-typed native snippets. They are being migrated, a few at a time,
 * into real files in each package's own test tree — the same move Blocks made. A file here can hold many
 * examples, each wrapped in `kx-usage:<demo-key>` … `kx-usage:end`, where <demo-key> is the key
 * `platform-code.ts` and the demo registry already use ("button-demo").
 *
 * Angular is the one platform that is fully migrated: every Angular snippet the site shows comes from here,
 * because the package was built after this pipeline existed and never accumulated hand-written strings.
 *
 * `check-platform-code.mjs` prefers a generated example over the hand-written snippet and fails when the two
 * disagree, so a migrated snippet can never drift. Nothing here writes code; it only copies it.
 */
import { readFileSync, writeFileSync, readdirSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const CHECK = process.argv.includes("--check");
const OUT = "apps/web/src/registry/usage-examples.generated.ts";

/** Platform tab key → where that platform's usage examples live, and the file extension. */
const SOURCES = {
  angular: { dir: "packages/ui-angular/src/usage", ext: ".ts" },
  swift: { dir: "packages/ui-swiftui/Tests/KinetixUITests/Usage", ext: ".swift" },
  kotlin: { dir: "packages/ui-compose/ui/src/test/kotlin/com/kinetixui/ui/usage", ext: ".kt" },
  dart: { dir: "packages/ui-flutter/test/usage", ext: ".dart" },
};
/** Tab order on the site — React is the canonical snippet and comes from the demo registry, not from here. */
const ORDER = ["angular", "swift", "kotlin", "dart"];

/**
 * Two marker spellings. An Angular example's useful part is its TEMPLATE, and inside a template literal a
 * `//` line is markup, not a comment — `<!-- … -->` is a real HTML comment there, renders as nothing, and
 * lets the region be exactly the lines a reader would type.
 *
 * (?!end) so the closing marker is never read as a region named "end".
 */
const START = /(?:\/\/|<!--) kx-usage:(?!end\b)([a-z0-9-]+)\s*(?:-->)?\s*$/;
const END = /(?:\/\/|<!--) kx-usage:end\s*(?:-->)?\s*$/;

/**
 * Strip the indentation a region carries only because it sits inside a class body or a template literal. The
 * shallowest non-blank line decides, so relative indentation inside the snippet survives: a reader copying an
 * example should not have to re-indent it, and should not lose its structure either.
 */
function dedent(code) {
  const indents = code
    .split("\n")
    .filter((l) => l.trim())
    .map((l) => l.match(/^\s*/)[0].length);
  const cut = indents.length ? Math.min(...indents) : 0;
  return cut
    ? code
        .split("\n")
        .map((l) => l.slice(cut))
        .join("\n")
    : code;
}

/** Every `kx-usage:<key>` block in one file, keyed by demo key. Relative indentation is preserved. */
function extractFile(text, relPath, into, platform) {
  const lines = text.split("\n");
  let key = null;
  let buf = [];
  for (const line of lines) {
    const s = line.match(START);
    if (s) {
      if (key) throw new Error(`${relPath}: kx-usage:${s[1]} opened while ${key} was still open`);
      key = s[1];
      buf = [];
      continue;
    }
    if (END.test(line)) {
      if (!key) throw new Error(`${relPath}: kx-usage:end with nothing open`);
      const code = dedent(buf.join("\n").replace(/^\n+|\n+$/g, ""));
      if (!code.trim()) throw new Error(`${relPath}: kx-usage:${key} is empty`);
      if (into[key]?.[platform]) throw new Error(`${relPath}: kx-usage:${key} is defined twice for ${platform}`);
      (into[key] ||= {})[platform] = code;
      key = null;
      continue;
    }
    if (key) buf.push(line);
  }
  if (key) throw new Error(`${relPath}: kx-usage:${key} was never closed`);
}

const examples = {};
const files = [];
for (const platform of ORDER) {
  const { dir, ext } = SOURCES[platform];
  if (!existsSync(`${root}/${dir}`)) continue;
  for (const f of readdirSync(`${root}/${dir}`).filter((n) => n.endsWith(ext)).sort()) {
    const rel = `${dir}/${f}`;
    files.push(rel);
    extractFile(readFileSync(`${root}/${rel}`, "utf8"), rel, examples, platform);
  }
}

const keys = Object.keys(examples).sort();
const GENERATED = "GENERATED by `pnpm gen:usage` from the kx-usage regions of the packages' own compiled sources. Edit those, not this file.";
const body = `/**
 * ${GENERATED}
 *
 * Each string below was extracted from a file its platform's CI compiles, so a snippet shown on a component
 * page cannot describe an API that no longer exists. \`check:platform-code\` prefers these over the
 * hand-written entries in platform-code.ts and fails if the two disagree.
 *
${files.map((f) => ` * ${f}`).join("\n")}
 */
export const usageExamples: Record<string, Partial<Record<"angular" | "swift" | "kotlin" | "dart", string>>> = {
${keys
  .map(
    (k) =>
      `  ${JSON.stringify(k)}: {\n${ORDER.filter((p) => examples[k][p])
        .map((p) => `    ${JSON.stringify(p)}: ${JSON.stringify(examples[k][p])},`)
        .join("\n")}\n  },`,
  )
  .join("\n")}
};
`;

if (CHECK) {
  const current = existsSync(`${root}/${OUT}`) ? readFileSync(`${root}/${OUT}`, "utf8") : "";
  if (current !== body) {
    console.error(`  x ${OUT} is stale — run \`pnpm gen:usage\``);
    process.exit(1);
  }
} else {
  writeFileSync(`${root}/${OUT}`, body);
}
const perPlatform = ORDER.map((p) => `${p} ${keys.filter((k) => examples[k][p]).length}`).join(", ");
console.log(`${CHECK ? "check:usage ok" : "gen:usage"} — ${keys.length} demo keys with compiled examples (${perPlatform}).`);
