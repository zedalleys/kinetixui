/**
 * report-block-parity.mjs — the cross-platform block matrix, as Markdown.
 *
 *   node scripts/report-block-parity.mjs
 *
 * Every block on every platform: its evidence level and the block's own tests, split into observed (a browser
 * or a device) and headless. Derived entirely from verification.json, which gen-verification.mjs writes from
 * the repository, so it cannot describe a state the repository is not in. Nothing here changes a level.
 */
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const v = JSON.parse(readFileSync(`${root}/verification.json`, "utf8"));
const PLATFORMS = ["React", "Angular", "SwiftUI", "Compose", "Flutter"];
const LABEL = {
  "not-implemented": "Not implemented",
  "not-verified": "Not verified",
  source: "Source present",
  build: "Build verified",
  runtime: "Runtime verified",
};

/** I/A for interaction/accessibility; ✓ when observed in a runtime environment, h when headless only. */
const tests = (e) =>
  ["interaction", "accessibility"]
    .filter((k) => e[k]?.length)
    .map((k) => `${k[0].toUpperCase()}${e[k].some((r) => v.runtimeEnvironments.includes(r.environment)) ? "✓" : "h"}`)
    .join(" ");

const lines = [
  "# Block parity matrix",
  "",
  "Generated by `node scripts/report-block-parity.mjs` from `verification.json`.",
  "",
  `Each cell is the level, then the block's own tests: I = interaction, A = accessibility; ✓ = observed in ${v.runtimeEnvironments.join(", ")}, h = headless only. No second part means no block-level test.`,
  "",
  `| Block | ${PLATFORMS.join(" | ")} |`,
  `|---|${PLATFORMS.map(() => "---").join("|")}|`,
];
for (const [slug, b] of Object.entries(v.blocks))
  lines.push(
    `| ${b.title} (\`${slug}\`) | ${PLATFORMS.map((p) => {
      const e = b.platforms[p] ?? { level: "not-implemented" };
      const t = tests(e);
      return LABEL[e.level] + (t ? ` · ${t}` : "");
    }).join(" | ")} |`,
  );
lines.push("", "## Totals", "", `| Platform | ${Object.values(LABEL).join(" | ")} |`, `|---|${Object.keys(LABEL).map(() => "---").join("|")}|`);
for (const p of PLATFORMS) lines.push(`| ${p} | ${Object.keys(LABEL).map((l) => v.blockTotals[p]?.[l] ?? 0).join(" | ")} |`);
console.log(lines.join("\n"));
