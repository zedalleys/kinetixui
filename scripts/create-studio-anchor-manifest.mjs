#!/usr/bin/env node
// Derive the Create Studio mutation-anchor manifest FROM the control runners, and prove that each
// anchor can reject its own mutation (M5.24, after Codex's P2 on PR #661).
//
// WHY THIS EXISTS. The source-integrity gate asserted a hand-curated set of substrings. Codex
// showed that three real runner mutations slipped through it:
//   * `staleDraft` is still present in `const staleDraft = false;`;
//   * the confirmed-save reset line appears at six sites, and a control changes one of them;
//   * one control's mutation had no anchor at all.
// A curated list cannot be trusted to stay complete, so the anchors are now GENERATED from the
// runners (`DUMP_ANCHORS=1` makes each control dump its own `file`, `old`, `new` and label and run
// nothing), and each entry is checked for an effective detector:
//
//   presence — after the mutation the `old` string is gone, so asserting it is PRESENT rejects it
//   absence  — the `new` string does not occur in the pristine file, so asserting it is ABSENT
//              rejects it. This is what catches a PURELY ADDITIVE mutation, which no presence
//              assertion can ever see.
//
// An entry with neither detector is a hole, and `--check` fails naming it rather than rounding it
// up to a pass.
//
//   node scripts/create-studio-anchor-manifest.mjs --write   regenerate the committed manifest
//   node scripts/create-studio-anchor-manifest.mjs --check    manifest is the fixed point of the
//                                                             runners, and every entry detects
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync, existsSync } from "node:fs";

const MANIFEST = "scripts/create-studio-mutation-anchors.json";
const RUNNERS = [
  "scripts/create-studio-save-state-controls.sh",
  "scripts/create-studio-resilience-controls.sh",
  "scripts/create-studio-error-boundary-controls.sh",
  "scripts/create-studio-recovery-exit-controls.sh",
];

const mode = process.argv[2] ?? "--check";
if (!["--check", "--write"].includes(mode)) {
  console.error("usage: create-studio-anchor-manifest.mjs --check|--write");
  process.exit(2);
}

function dump(runner) {
  const out = execFileSync("bash", [runner], {
    env: { ...process.env, DUMP_ANCHORS: "1" },
    encoding: "utf8",
    maxBuffer: 32 * 1024 * 1024,
  });
  const rows = [];
  for (const line of out.split("\n")) {
    if (!line.includes("\t")) continue;
    const [file, old64, new64, label64] = line.split("\t");
    rows.push({
      runner,
      label: Buffer.from(label64, "base64").toString("utf8"),
      file,
      old: Buffer.from(old64, "base64").toString("utf8"),
      new: Buffer.from(new64, "base64").toString("utf8"),
    });
  }
  if (rows.length === 0) throw new Error(`${runner} dumped no anchors — the DUMP_ANCHORS hook is missing or broken`);
  return rows;
}

// For each dumped mutation, decide which detectors actually work, by APPLYING the mutation to the
// real file in memory. Nothing is written to the working tree.
function classify(rows) {
  const problems = [];
  const entries = rows.map(row => {
    if (!existsSync(row.file)) {
      problems.push(`${row.label}: ${row.file} does not exist`);
      return null;
    }
    const pristine = readFileSync(row.file, "utf8");
    if (!pristine.includes(row.old)) {
      problems.push(`${row.label}: its anchor is not in ${row.file} — the control itself would be BROKEN`);
      return null;
    }
    const mutated = pristine.replace(row.old, row.new);
    const detectors = [];
    // presence: assert `old` is there. Works only if the mutation really removes every copy.
    if (!mutated.includes(row.old)) detectors.push("presence");
    // absence: assert `new` is not there. Works only if `new` is not legitimate source already.
    if (!pristine.includes(row.new) && mutated.includes(row.new)) detectors.push("absence");
    if (detectors.length === 0) {
      problems.push(
        `${row.label}: NO EFFECTIVE DETECTOR — the mutation neither removes its anchor nor adds a string absent from ${row.file}`,
      );
      return null;
    }
    return { ...row, detectors };
  });
  return { entries: entries.filter(Boolean), problems };
}

const rows = RUNNERS.flatMap(dump);
const { entries, problems } = classify(rows);
const manifest = {
  note:
    "GENERATED by scripts/create-studio-anchor-manifest.mjs from the control runners. Do not hand-edit: " +
    "regenerate with --write. Each entry says how the source-integrity gate rejects that control's " +
    "mutation if it is ever left behind.",
  generatedFrom: RUNNERS,
  entries: entries
    .map(e => ({
      runner: e.runner,
      label: e.label,
      file: e.file,
      detectors: e.detectors,
      present: e.detectors.includes("presence") ? e.old : undefined,
      absent: e.detectors.includes("absence") ? e.new : undefined,
    }))
    .sort((a, b) => (a.file + a.label).localeCompare(b.file + b.label)),
};
const serialized = JSON.stringify(manifest, null, 2) + "\n";

if (problems.length > 0) {
  for (const p of problems) console.error(`ANCHOR PROBLEM  ${p}`);
  console.error(
    `\n${problems.length} control mutation(s) cannot be rejected by any anchor. This is a hole in the` +
      " source-integrity gate, not a formatting issue: fix the control's anchor or the mutation, then regenerate.",
  );
  process.exit(1);
}

if (mode === "--write") {
  writeFileSync(MANIFEST, serialized);
  console.log(`wrote ${MANIFEST} — ${manifest.entries.length} anchors from ${RUNNERS.length} runners`);
  process.exit(0);
}

if (!existsSync(MANIFEST)) {
  console.error(`${MANIFEST} is missing — run --write`);
  process.exit(1);
}
if (readFileSync(MANIFEST, "utf8") !== serialized) {
  console.error(
    `${MANIFEST} is NOT the fixed point of the runners: a control was added, removed or changed without` +
      " regenerating it. Run --write and commit the result.",
  );
  process.exit(1);
}
const byDetector = manifest.entries.reduce((acc, e) => {
  const k = e.detectors.join("+");
  acc[k] = (acc[k] ?? 0) + 1;
  return acc;
}, {});
console.log(
  `check:create-anchors — ${manifest.entries.length} control mutations, every one rejectable ` +
    `(${Object.entries(byDetector).map(([k, v]) => `${v} by ${k}`).join(", ")}).`,
);
