import { chromium } from "playwright";
const b = await chromium.launch({ headless: true, executablePath: "/opt/pw-browsers/chromium" });
const p = await (await b.newContext({ viewport: { width: 1440, height: 1000 } })).newPage();
p.on("pageerror", e => console.log("PAGEERROR", e.message));
p.on("console", m => { if (m.type() === "error") console.log("CONSOLE", m.text()); });
await p.goto("http://127.0.0.1:3137/create/studio");
const s = p.locator(".create-studio");
await s.getByRole("button", { name: "Start local workspace" }).click();
await s.getByLabel("New product name").fill("Probe2");
await s.getByRole("button", { name: "New product", exact: true }).click();
await s.getByRole("button", { name: "Add Button", exact: true }).waitFor();
await s.getByRole("button", { name: "Layers", exact: true }).click();
const tree = s.getByRole("tree", { name: "Screen layers" });
await tree.getByRole("treeitem").nth(1).click();
await s.getByRole("button", { name: "Library", exact: true }).click();
const h = s.getByRole("slider", { name: /frame width/ });
console.log("handle count", await h.count(), "box", JSON.stringify(await h.boundingBox()));
const box = await h.boundingBox();
const cx = box.x + box.width / 2, cy = box.y + box.height / 2;
console.log("topmost at point:", await p.evaluate(([x,y]) => { const el = document.elementFromPoint(x,y); return el ? `${el.tagName}.${el.className} resize=${el.getAttribute("data-studio-resize")}` : "none"; }, [cx, cy]));
await p.mouse.move(cx, cy); await p.mouse.down();
await p.mouse.move(cx + 20, cy, { steps: 3 });
await p.mouse.move(cx + 60, cy, { steps: 8 });
await p.waitForTimeout(150);
console.log("status:", JSON.stringify(await s.locator(".studio-announcement").last().innerText()));
console.log("guides:", await s.locator(".studio-guide").count());
await p.mouse.up();
await p.waitForTimeout(150);
console.log("valuenow after:", await h.getAttribute("aria-valuenow"));
await b.close();
