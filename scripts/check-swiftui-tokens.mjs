/**
 * check:swiftui-tokens — corners and shadows in packages/ui-swiftui come from the theme.
 *
 *   node scripts/check-swiftui-tokens.mjs
 *
 * Until radius and elevation were themeable, every `Kinetix*` view wrote them as literals. That is
 * why the SwiftUI exporter says radius does not travel: there was nowhere for it to land. Now there
 * is, and the interesting failure is the slow one — a new component, or a hurried fix, going back to
 * `cornerRadius: 16` and taking that corner off the theme without anyone noticing.
 *
 * This runs on Linux with the rest of the guardrails rather than inside `swift test`, so it checks
 * every pull request instead of only the ones that trip the macOS workflow's path filter.
 *
 * Two allowlists, and both are the documentation:
 *
 *   OFF_LADDER   corners at 6, which is not a step on the 4/8/12/16 ladder. Left alone deliberately
 *                — moving them is a visual change, and a refactor is the wrong place to make one.
 *   LITERAL      shadows that are not elevation steps: a switch knob's depth inside its track, and a
 *                colour swatch separating itself from its neighbour.
 *
 * A file leaving an allowlist is fine and needs no edit here. A file joining one needs a reason, and
 * writing that reason down is the point.
 */
import { readFileSync, readdirSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const dir = `${root}packages/ui-swiftui/Sources/KinetixUI`;

/** Corners that are not on the ladder, with the count each file is allowed. */
const OFF_LADDER = {
  "AppBar.swift": 1,
  "ColorPicker.swift": 2,
  "FileUpload.swift": 2,
  "InputOtp.swift": 2,
  "Sidebar.swift": 1,
};

/** Shadows that are deliberately not an elevation step. */
const LITERAL_SHADOWS = {
  "Switch.swift": 1,
  "ColorPicker.swift": 1,
  // The modifier that applies a step has to call `.shadow` — it is the implementation.
  "Elevation.swift": 1,
};

/** Generated files are not hand-written and are not this check's business. */
const GENERATED = /generated by Style Dictionary|do not hand-edit|Do not edit/i;

/** The two files that define the theme surfaces, and therefore describe the thing they implement. */
const DEFINES_THE_TOKENS = new Set(["Elevation.swift", "Radii.swift", "Theme.swift"]);

/**
 * Comments are prose, not calls.
 *
 * Without this, `Elevation.swift` failed its own check twice: its header explains that components
 * "carried a hand-tuned `.shadow(...)`" and quotes the Card comment that said there was "no
 * elevation scale yet". Both are the documentation of the fix, counted as the defect.
 */
const stripComments = (source) =>
  source
    .replace(/\/\*[\s\S]*?\*\//g, " ")
    .split("\n")
    .map((line) => line.replace(/\/\/.*$/, ""))
    .join("\n");

const errors = [];
const note = [];

const files = readdirSync(dir).filter((f) => f.endsWith(".swift"));
if (files.length < 50) {
  console.error(`Only ${files.length} Swift sources found in ${dir} — that is a broken checkout, not a clean run.`);
  process.exit(1);
}

let themedCorners = 0;
let themedShadows = 0;

for (const name of files) {
  const raw = readFileSync(`${dir}/${name}`, "utf8");
  if (GENERATED.test(raw.slice(0, 400))) continue;
  const source = stripComments(raw);

  themedCorners += (source.match(/cornerRadius: radii\./g) ?? []).length;
  themedShadows += (source.match(/\.kinetixElevation\(/g) ?? []).length;

  // ---- corners -------------------------------------------------------------
  const literals = [...source.matchAll(/cornerRadius: (\d+)\b/g)].map((m) => Number(m[1]));
  const onLadder = literals.filter((v) => [4, 8, 12, 16].includes(v));
  const off = literals.filter((v) => ![4, 8, 12, 16].includes(v));

  for (const value of onLadder) {
    errors.push(
      `${name}: cornerRadius: ${value} is a ladder step written as a literal — use \`radii.field\` (4), ` +
        `\`radii.control\` (8), \`radii.container\` (12) or \`radii.surface\` (16) so a theme can change it.`,
    );
  }

  const allowedOff = OFF_LADDER[name] ?? 0;
  if (off.length > allowedOff) {
    errors.push(
      `${name}: ${off.length} off-ladder corner(s) (${[...new Set(off)].join(", ")}), ${allowedOff} allowed. ` +
        `A new one needs either a ladder step or a line in OFF_LADDER saying why it is not one.`,
    );
  } else if (off.length < allowedOff) {
    note.push(`${name}: ${allowedOff - off.length} off-ladder corner(s) gone — trim OFF_LADDER.`);
  }

  // ---- shadows -------------------------------------------------------------
  const shadows = (source.match(/\.shadow\(/g) ?? []).length;
  const allowedShadow = LITERAL_SHADOWS[name] ?? 0;
  if (shadows > allowedShadow) {
    errors.push(
      `${name}: ${shadows} literal \`.shadow(\` call(s), ${allowedShadow} allowed. ` +
        `Use \`.kinetixElevation(elevations.sm|md|lg|xl)\`, or add a line to LITERAL_SHADOWS with the reason.`,
    );
  } else if (shadows < allowedShadow) {
    note.push(`${name}: ${allowedShadow - shadows} literal shadow(s) gone — trim LITERAL_SHADOWS.`);
  }

  // ---- the comments that described the old gap ----------------------------
  if (DEFINES_THE_TOKENS.has(name)) continue;
  for (const stale of [/shadow-sm approx/i, /shadow-lg approx/i, /no elevation scale yet/i]) {
    if (stale.test(raw)) {
      errors.push(`${name}: still says ${stale} — the elevation scale exists now (Elevation.swift).`);
    }
  }
}

/** A guard that passes because nothing is themed would be worse than no guard. */
if (themedCorners === 0 || themedShadows === 0) {
  errors.push(
    `Found ${themedCorners} themed corner(s) and ${themedShadows} themed shadow(s). ` +
      `If components stopped reading the theme, radius and elevation are not really supported.`,
  );
}

if (note.length) {
  console.log("notes (not failures):");
  for (const n of note) console.log(`  · ${n}`);
}

if (errors.length) {
  console.error(`\ncheck:swiftui-tokens failed (${errors.length}):`);
  for (const e of errors) console.error(`  ✗ ${e}`);
  process.exit(1);
}

console.log(
  `check:swiftui-tokens ok — ${themedCorners} corners and ${themedShadows} shadows read the theme; ` +
    `${Object.values(OFF_LADDER).reduce((a, b) => a + b, 0)} documented off-ladder corners, ` +
    `${Object.values(LITERAL_SHADOWS).reduce((a, b) => a + b, 0)} documented literal shadows.`,
);
