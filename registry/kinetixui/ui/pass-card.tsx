"use client";

import * as React from "react";
import { cn } from "@/lib/utils";

/**
 * PassCard — the foundation for anything a person carries and presents: a boarding pass, an event or rail
 * ticket, a parking permit, a voucher or gift card, a membership card, a reservation confirmation.
 *
 * Those are not separate components. Every one of them is the same anatomy with different words:
 *
 *   PassCardHeader        who issued it and what it is, plus room for a status (compose a `Tag`)
 *   PassCardFields        the facts a person looks for at a glance — Gate, Seat, Row, Plate, Valid until
 *   PassCardDivider       the tear line between the pass and its stub
 *   PassCardCode          the scannable code, as SUPPLIED, with a text alternative and a human-readable fallback
 *   PassCardFooter        terms, small print, actions
 *
 * so a BoardingPass, an EventTicket or a ParkingPass is a composition of these parts (see the docs page),
 * not a component with "flight" in its props. That is the rule this foundation exists to keep.
 *
 * What it deliberately does not do:
 *   - encode anything. A barcode or QR code is generated by the product (or the issuer) and passed in as an
 *     image or SVG. Inventing an encoder would also invent a security model nobody has reviewed.
 *   - recolour the code for dark mode. A scanner needs dark modules on a light quiet zone, so supply the code
 *     with its own background; the component never inverts it.
 *   - pretend a status. Validity is a field (`<time>` values); expiry is something the product decides.
 *
 * Semantics: an `<article>` named by its title, fields as a `<dl>`, the code as a `<figure>` whose visual is an
 * image named by `label` and whose caption is the readable value.
 */
const PassCardContext = React.createContext<{ titleId?: string; setTitleId: (id: string | undefined) => void } | null>(null);

const PassCard = React.forwardRef<HTMLElement, React.HTMLAttributes<HTMLElement>>(
  ({ className, children, ...props }, ref) => {
    const [titleId, setTitleId] = React.useState<string | undefined>(undefined);
    const ctx = React.useMemo(() => ({ titleId, setTitleId }), [titleId]);
    return (
      <PassCardContext.Provider value={ctx}>
        <article
          ref={ref}
          aria-labelledby={props["aria-label"] ? undefined : titleId}
          className={cn(
            "flex w-full min-w-0 flex-col overflow-hidden rounded-xl border border-border/50 bg-card font-sans text-card-foreground shadow-md",
            className,
          )}
          {...props}
        >
          {children}
        </article>
      </PassCardContext.Provider>
    );
  },
);
PassCard.displayName = "PassCard";

const PassCardHeader = React.forwardRef<HTMLDivElement, React.HTMLAttributes<HTMLDivElement>>(
  ({ className, ...props }, ref) => (
    <div
      ref={ref}
      className={cn("flex min-w-0 flex-wrap items-start justify-between gap-x-4 gap-y-2 px-5 pb-3 pt-5", className)}
      {...props}
    />
  ),
);
PassCardHeader.displayName = "PassCardHeader";

type HeadingLevel = 2 | 3 | 4 | 5 | 6;

export interface PassCardTitleProps extends React.HTMLAttributes<HTMLHeadingElement> {
  /** Default 3 — a pass is usually one item inside a page or a list. */
  level?: HeadingLevel;
}

/** Names the pass. The card is labelled by it, so a list of passes reads as a list of named articles. */
const PassCardTitle = React.forwardRef<HTMLHeadingElement, PassCardTitleProps>(
  ({ className, level = 3, id, ...props }, ref) => {
    const generated = React.useId();
    const titleId = id ?? generated;
    const ctx = React.useContext(PassCardContext);
    const setTitleId = ctx?.setTitleId;
    React.useEffect(() => {
      setTitleId?.(titleId);
      return () => setTitleId?.(undefined);
    }, [setTitleId, titleId]);
    const Heading = `h${level}` as const;
    return <Heading ref={ref} id={titleId} className={cn("text-title-md font-semibold text-foreground", className)} {...props} />;
  },
);
PassCardTitle.displayName = "PassCardTitle";

/** The line under the title — the issuer, the holder's name, the event or the route. */
const PassCardDescription = React.forwardRef<HTMLParagraphElement, React.HTMLAttributes<HTMLParagraphElement>>(
  ({ className, ...props }, ref) => (
    <p ref={ref} className={cn("text-body-sm text-muted-foreground", className)} {...props} />
  ),
);
PassCardDescription.displayName = "PassCardDescription";

/**
 * The fact grid. Columns are as many as fit at a minimum width in rem, so at 200% text or on a phone they
 * fall to fewer columns instead of truncating a gate number or a plate.
 */
const PassCardFields = React.forwardRef<HTMLDListElement, React.HTMLAttributes<HTMLDListElement>>(
  ({ className, ...props }, ref) => (
    <dl
      ref={ref}
      className={cn("grid grid-cols-[repeat(auto-fit,minmax(min(100%,7rem),1fr))] gap-x-4 gap-y-3 px-5 py-3", className)}
      {...props}
    />
  ),
);
PassCardFields.displayName = "PassCardFields";

export interface PassCardFieldProps extends Omit<React.HTMLAttributes<HTMLDivElement>, "children"> {
  label: React.ReactNode;
  /** Use `<time dateTime>` for dates and times so they are machine-readable. */
  children: React.ReactNode;
  /** For the one or two values a person looks for first — a gate, a seat, a bay. */
  emphasis?: boolean;
}

const PassCardField = React.forwardRef<HTMLDivElement, PassCardFieldProps>(
  ({ className, label, children, emphasis = false, ...props }, ref) => (
    <div ref={ref} className={cn("flex min-w-0 flex-col gap-0.5", className)} {...props}>
      <dt className="text-label-sm text-muted-foreground">{label}</dt>
      <dd
        className={cn(
          "min-w-0 text-foreground [overflow-wrap:anywhere]",
          emphasis ? "text-title-lg font-semibold tabular-nums" : "text-body-md font-medium",
        )}
      >
        {children}
      </dd>
    </div>
  ),
);
PassCardField.displayName = "PassCardField";

/**
 * The tear line between a pass and its stub: a dashed rule on the border token. A real `<hr>`, so the stub
 * is announced as a separate part. (Punched notches were left out: painting them in the page colour breaks
 * on any other surface, and a mask is a visual flourish this foundation does not need.)
 */
const PassCardDivider = React.forwardRef<HTMLHRElement, React.HTMLAttributes<HTMLHRElement>>(
  ({ className, ...props }, ref) => (
    <hr
      ref={ref}
      className={cn("mx-5 my-1 border-0 border-t-2 border-dashed border-border", className)}
      {...props}
    />
  ),
);
PassCardDivider.displayName = "PassCardDivider";

export interface PassCardCodeProps extends Omit<React.HTMLAttributes<HTMLElement>, "children"> {
  /** What the code is, for people who cannot see it — "Boarding pass QR code". */
  label: string;
  /** The barcode or QR code, generated elsewhere and passed in as an `<img>` or `<svg>`. */
  children: React.ReactNode;
  /** The human-readable value printed under the code, for when it will not scan. A string or a `<ReferenceCode>`. */
  value?: React.ReactNode;
}

const PassCardCode = React.forwardRef<HTMLElement, PassCardCodeProps>(
  ({ className, label, children, value, ...props }, ref) => (
    <figure ref={ref} className={cn("flex flex-col items-center gap-2 px-5 py-4", className)} {...props}>
      <div role="img" aria-label={label} className="max-w-full [&>img]:h-auto [&>img]:max-w-full [&>svg]:h-auto [&>svg]:max-w-full">
        {children}
      </div>
      {value && (
        <figcaption className="max-w-full text-center font-mono text-label-md tracking-wide text-muted-foreground [overflow-wrap:anywhere]">
          {value}
        </figcaption>
      )}
    </figure>
  ),
);
PassCardCode.displayName = "PassCardCode";

const PassCardFooter = React.forwardRef<HTMLDivElement, React.HTMLAttributes<HTMLDivElement>>(
  ({ className, ...props }, ref) => (
    <div
      ref={ref}
      className={cn("flex min-w-0 flex-wrap items-center gap-3 border-t border-border/60 bg-muted/30 px-5 py-3 text-body-sm text-muted-foreground", className)}
      {...props}
    />
  ),
);
PassCardFooter.displayName = "PassCardFooter";

export {
  PassCard,
  PassCardHeader,
  PassCardTitle,
  PassCardDescription,
  PassCardFields,
  PassCardField,
  PassCardDivider,
  PassCardCode,
  PassCardFooter,
};
