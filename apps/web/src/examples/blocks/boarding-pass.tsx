/**
 * One boarding pass, composed from the PassCard foundation. A rail or event ticket, a parking permit or a
 * venue credential is this block with different words — the anatomy does not change, which is why there is
 * no component with "flight" in its props.
 *
 * Every value arrives supplied: the block looks nothing up, computes no time zone and encodes nothing. The
 * scannable code is generated by the product or the issuer and passed in as `code`; the placeholder below
 * stands in for it on this page, and PassCard never inverts it for dark mode because a scanner needs dark
 * modules on a light quiet zone.
 *
 * The route is written as words ("Riyadh (RUH) to Cairo (CAI)") rather than with an arrow, so it reads
 * correctly in both directions instead of pointing the wrong way in Arabic or Hebrew. Gate, seat and group
 * are the three values a traveller looks for at a glance, so they carry PassCardField's emphasis; the fact
 * grid reflows to fewer columns at 200% text rather than truncating a gate number. Boarding status is a word
 * in a Tag, not a colour. The confirmation code is a ReferenceCode, because the one thing a traveller has to
 * read out or paste is the code, and a copy that silently fails is worse than no copy button.
 *
 * All data here is fictional, Kinetix Air included.
 */
export function BoardingPassBlock({ code }: { code?: React.ReactNode }) {
  return (
    <PassCard className="max-w-sm">
      <PassCardHeader>
        <div className="flex min-w-0 flex-col gap-1">
          <PassCardTitle>Boarding pass</PassCardTitle>
          <PassCardDescription>Kinetix Air · Riyadh (RUH) to Cairo (CAI)</PassCardDescription>
        </div>
        {/* A word, not a colour. */}
        <Tag variant="secondary">Boarding</Tag>
      </PassCardHeader>

      <PassCardFields>
        <PassCardField label="Passenger">Amira Haddad</PassCardField>
        <PassCardField label="Flight">KX 1180</PassCardField>
        <PassCardField label="Boards">
          {/* Its own `dir="auto"` run: a Latin date begins with a digit, and in an RTL paragraph the bidi
              algorithm would move that digit to the other end — "2 Apr, 06:15" reads as "Apr, 06:15 2". */}
          <time dateTime="2026-04-02T06:15" dir="auto">
            2 Apr, 06:15
          </time>
        </PassCardField>
        <PassCardField label="Gate" emphasis>
          C21
        </PassCardField>
        <PassCardField label="Seat" emphasis>
          9A
        </PassCardField>
        <PassCardField label="Group" emphasis>
          3
        </PassCardField>
      </PassCardFields>

      <PassCardDivider />

      <PassCardCode
        label="Boarding pass QR code"
        value={<ReferenceCode label="Confirmation code" value="KX7F2Q9" />}
      >
        {code ?? <SuppliedCodePlaceholder />}
      </PassCardCode>

      <PassCardFooter>The gate closes 20 minutes before departure.</PassCardFooter>
    </PassCard>
  );
}

